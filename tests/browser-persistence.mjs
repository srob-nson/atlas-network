import assert from 'node:assert/strict';

const pages = await (await fetch('http://127.0.0.1:9223/json/list')).json();
const page = pages.find(p => p.type === 'page');
const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
let id = 0; const pending = new Map();
socket.onmessage = event => { const message = JSON.parse(event.data); if (pending.has(message.id)) { pending.get(message.id)(message.result); pending.delete(message.id); } else if (message.method === 'Page.javascriptDialogOpening') send('Page.handleJavaScriptDialog', { accept: true }); };
const send = (method, params = {}) => new Promise(resolve => { const n = ++id; pending.set(n, resolve); socket.send(JSON.stringify({ id: n, method, params })); });
const evaluate = expression => send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }).then(result => { if (result.exceptionDetails) throw Error(result.exceptionDetails.exception?.description); return result.result.value; });
const waitFor = async expression => { for (let n = 0; n < 100; n++) { if (await evaluate(expression)) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw Error(`Timed out: ${expression}`); };
const reload = async () => { await send('Page.reload', { ignoreCache: true }); await waitFor(`document.querySelector('#breadcrumb-project')?.textContent`); };

await send('Page.enable');
await send('Page.handleJavaScriptDialog', { accept: true });
await send('Page.navigate', { url: 'about:blank' });
await send('Page.navigate', { url: 'http://127.0.0.1:5173/dist/' });
await waitFor(`document.querySelector('#breadcrumb-project')?.textContent`);
console.log('Preparing migration');
await new Promise(resolve => setTimeout(resolve, 500));
await evaluate(`new Promise((resolve, reject) => { const request = indexedDB.open('titan-workspace'); request.onsuccess = () => { const db = request.result, tx = db.transaction('workspace', 'readwrite'); tx.objectStore('workspace').clear(); tx.oncomplete = () => { db.close(); resolve(); }; tx.onerror = reject; }; request.onerror = reject; })`);
await evaluate(`localStorage.clear(); localStorage.setItem('titan-project-v1', JSON.stringify({name:'Legacy',zones:[],assets:[],cables:[]}))`);
const injection = await send('Page.addScriptToEvaluateOnNewDocument', { source: `const originalTransaction = IDBDatabase.prototype.transaction; IDBDatabase.prototype.transaction = function(store, mode) { if (mode === 'readwrite') throw new Error('Storage unavailable'); return originalTransaction.call(this, store, mode); };` });
await send('Page.navigate', { url: 'about:blank' });
await send('Page.navigate', { url: 'http://127.0.0.1:5173/dist/' });
await waitFor(`document.querySelector('#breadcrumb-project')?.textContent === 'Legacy'`);
await waitFor(`document.querySelector('#save-status').textContent.includes('Not saved')`);
assert.ok(await evaluate(`localStorage.getItem('titan-project-v1')`));
await send('Page.removeScriptToEvaluateOnNewDocument', { identifier: injection.identifier });
await send('Page.navigate', { url: 'about:blank' });
await send('Page.navigate', { url: 'http://127.0.0.1:5173/dist/' });
await waitFor(`document.querySelector('#breadcrumb-project')?.textContent === 'Legacy'`);
console.log('Migrated legacy project');
await waitFor(`document.querySelector('#save-status').textContent === 'Saved locally'`);
await waitFor(`localStorage.getItem('titan-project-v1') === null`);
assert.equal(await evaluate(`localStorage.getItem('titan-project-v1')`), null);
await evaluate(`window.prompt = () => 'Persistent project'; document.querySelector('[data-action="new-project"]').click()`);
await waitFor(`document.querySelector('#save-status').textContent === 'Saved locally'`);
await evaluate(`document.querySelector('[data-action="add-asset"]').click(); document.querySelector('[data-action="auto-place"]').click()`);
await waitFor(`document.querySelector('#save-status').textContent === 'Saved locally'`);
assert.equal(await evaluate(`document.querySelector('#side-rack-count').textContent`), '00');
await reload();
await waitFor(`document.querySelector('#breadcrumb-project').textContent === 'Persistent project'`);
console.log('Reloaded project');
assert.equal(await evaluate(`document.querySelector('#equipment-count').textContent`), '1');

await evaluate(`window.exported = null; URL.createObjectURL = blob => { blob.text().then(text => window.exported = text); return 'blob:test'; }; HTMLAnchorElement.prototype.click = () => {}; document.querySelector('[data-action="export-project"]').click()`);
await waitFor(`window.exported !== null`);
const exported = JSON.parse(await evaluate('window.exported'));
assert.equal(exported.schemaVersion, 2);
assert.equal(exported.devices.length, 1);
await evaluate(`window.importError = ''; window.alert = message => { window.importError = message; }; { const input = document.querySelector('#project-file'), files = new DataTransfer(); files.items.add(new File([${JSON.stringify(JSON.stringify({...exported, schemaVersion: 999}))}], 'future.json', {type:'application/json'})); input.files = files.files; input.dispatchEvent(new Event('change')); }`);
await waitFor(`window.importError.length > 0`);
assert.equal(await evaluate(`document.querySelector('#project-select').options.length`), 2);
assert.equal(await evaluate(`document.querySelector('#breadcrumb-project').textContent`), 'Persistent project');
await evaluate(`{ const input = document.querySelector('#project-file'), files = new DataTransfer(); files.items.add(new File([${JSON.stringify(JSON.stringify(exported))}], 'project.json', {type:'application/json'})); input.files = files.files; input.dispatchEvent(new Event('change')); }`);
await waitFor(`document.querySelector('#project-select').options.length === 3`);
console.log('Imported project');
await waitFor(`document.querySelector('#save-status').textContent === 'Saved locally'`);
await reload();
await waitFor(`document.querySelector('#project-select').options.length === 3`);
assert.equal(await evaluate(`document.querySelector('#equipment-count').textContent`), '1');

await evaluate(`IDBDatabase.prototype.transaction = () => { throw new Error('Storage unavailable'); }; window.prompt = () => 'Unsaved'; document.querySelector('[data-action="rename-project"]').click()`);
console.log('Simulating storage failure');
await waitFor(`document.querySelector('#save-status').textContent.includes('Not saved')`);
assert.equal(await evaluate(`document.querySelector('#breadcrumb-project').textContent`), 'Unsaved');
await evaluate(`{ const input = document.querySelector('#project-file'), files = new DataTransfer(); files.items.add(new File([${JSON.stringify(JSON.stringify(exported))}], 'project.json', {type:'application/json'})); input.files = files.files; input.dispatchEvent(new Event('change')); }`);
await waitFor(`document.querySelector('#project-select').options.length === 4`);
await waitFor(`document.querySelector('#save-status').textContent.includes('Not saved')`);
assert.notEqual(await evaluate(`document.querySelector('#toast').textContent`), 'Project imported.');
console.log('Migration, IndexedDB reload, placement, JSON round trip and save failure passed.');
await send('Page.navigate', { url: 'about:blank' });
await send('Page.navigate', { url: 'http://127.0.0.1:5173/dist/' });
await waitFor(`document.querySelector('#project-select').options.length === 3`);
assert.equal(await evaluate(`document.querySelector('#breadcrumb-project').textContent`), 'Persistent project');
socket.close();
