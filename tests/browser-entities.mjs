// Uses an isolated local Chrome preview profile.
import assert from 'node:assert/strict';
import { browserEvaluate } from './browser-storage.mjs';
const pages = await (await fetch('http://127.0.0.1:9223/json/list')).json();
const socket = new WebSocket(pages.find(p => p.type === 'page').webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
let id = 0; const pending = new Map();
socket.onmessage = event => { const message = JSON.parse(event.data); if (pending.has(message.id)) { pending.get(message.id)(message.result); pending.delete(message.id); } };
const send = (method, params = {}) => new Promise(resolve => { const n = ++id; pending.set(n, resolve); socket.send(JSON.stringify({ id: n, method, params })); });
const evaluate = browserEvaluate(send);
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const field = async (name, value) => evaluate(`{ const el = document.querySelector(${JSON.stringify(name)}); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('change', { bubbles: true })); }`);
await send('Page.navigate', { url: 'http://127.0.0.1:5173/dist/' }); await wait(600);
await evaluate(`localStorage.setItem('titan-workspace-v2', JSON.stringify({projects:[{name:'Entities',buildings:[{id:'b',name:'Building',floors:[{id:'f',floorName:'Floor',zones:[],assets:[{id:'r',name:'Rack',type:'cabinet',rackUnits:12,placed:true,x:20,y:20},{id:'a',name:'Switch A',type:'switch',rackId:'',ports:[]},{id:'b',name:'Switch B',type:'switch',rackId:'',ports:[]}]}]}],cables:[{id:'legacy',from:'a',to:'b'}]}]})); location.reload()`); await wait(700);
await evaluate(`document.querySelector('[data-asset-select="a"]').click()`);
await field('[name="vendor"]', 'Example Networks');
await field('[name="model"]', 'S24');
await field('[name="portCount"]', '24');
assert.equal(await evaluate(`document.querySelectorAll('[data-port-field="name"]').length`), 24);
await field('[data-port-index="0"][data-port-field="name"]', 'Gi0/1');
await field('[data-port-index="0"][data-port-field="speed"]', '10 Gbps');
await field('[data-port-index="0"][data-port-field="media"]', 'fiber');
await field('[name="rackStart"]', '1'); await field('[name="rackHeight"]', '2'); await field('[name="rackId"]', 'r');
await evaluate(`document.querySelector('[data-asset-select="b"]').click()`);
await field('[name="portCount"]', '2');
await field('[name="rackStart"]', '2'); await field('[name="rackHeight"]', '2'); await field('[name="rackId"]', 'r');
assert.match(await evaluate(`document.querySelector('#toast').textContent`), /occupied/i);
assert.equal(await evaluate(`document.querySelector('[name="rackId"]').value`), '');
await field('[name="rackStart"]', '3'); await field('[name="rackId"]', 'r');
await evaluate(`document.querySelector('[data-action="show-racks"]').click(); document.querySelector('[data-rack-open="r"]').click()`);
assert.equal(await evaluate(`document.querySelectorAll('.rack-panel').length`), 2);
await evaluate(`document.querySelector('[data-port-device="a"][data-port-name="Gi0/1"]').dispatchEvent(new MouseEvent('click',{bubbles:true,detail:0}))`);
await field('#connect-to', '["b","1"]');
await wait(300);
const stored = await evaluate(`new Promise((resolve, reject) => { const open = indexedDB.open('titan-workspace'); open.onerror = reject; open.onsuccess = () => { const db = open.result, tx = db.transaction('workspace'), get = tx.objectStore('workspace').get('current'); tx.oncomplete = () => { db.close(); resolve(get.result); }; tx.onerror = reject; }; })`);
const project = stored.projects[0];
assert.equal(project.schemaVersion, 2);
assert.equal(project.devices.find(d => d.id === 'a').vendor, 'Example Networks');
assert.equal(project.ports.filter(p => p.deviceId === 'a').length, 24);
assert.equal(project.devices.find(d => d.id === 'b').rackStart, 3);
assert.deepEqual(project.ports.find(p => p.name === 'Gi0/1').media, 'fiber');
assert.equal(project.connections.find(c => c.id === 'legacy').from.portId, null);
const linked = project.connections.find(c => c.id !== 'legacy');
assert.equal(linked.from.portId, project.ports.find(p => p.deviceId === 'a' && p.name === 'Gi0/1').id);
assert.equal(linked.to.portId, project.ports.find(p => p.deviceId === 'b' && p.name === '1').id);
await evaluate(`document.querySelector('[data-action="close-dialog"]').click(); document.querySelector('[data-asset-select="a"]').click()`);
await field('[name="portCount"]', '0');
assert.match(await evaluate(`document.querySelector('#toast').textContent`), /connected/i);
assert.equal(await evaluate(`document.querySelector('[name="portCount"]').value`), '24');
await field('[data-port-index="0"][data-port-field="name"]', 'uplink');
await evaluate(`document.querySelector('[data-action="show-connections"]').click(); document.querySelector('[data-cable-select="legacy"]').click(); document.querySelector('[data-action="edit-connection-ports"]').click()`);
await evaluate(`{ for (const id of ['connect-from', 'connect-destination']) document.getElementById(id).selectedIndex = 1; document.querySelector('#connect-form').requestSubmit(); }`);
await wait(200);
await send('Page.reload', { ignoreCache: true }); await wait(700);
assert.equal(await evaluate(`document.querySelector('#breadcrumb-project').textContent`), 'Entities');
await evaluate(`document.querySelector('[data-asset-select="a"]').click()`);
assert.equal(await evaluate(`document.querySelector('[name="portCount"]').value`), '24');
assert.equal(await evaluate(`document.querySelector('[data-port-index="0"][data-port-field="name"]').value`), 'uplink');
const reloaded = await evaluate(`new Promise((resolve, reject) => { const open = indexedDB.open('titan-workspace'); open.onerror = reject; open.onsuccess = () => { const db = open.result, tx = db.transaction('workspace'), get = tx.objectStore('workspace').get('current'); tx.oncomplete = () => { db.close(); resolve(get.result.projects[0]); }; tx.onerror = reject; }; })`);
assert.equal(reloaded.connections.find(c => c.id === linked.id).from.portId, linked.from.portId);
assert.equal(reloaded.ports.find(p => p.id === linked.from.portId).name, 'uplink');
assert.ok(reloaded.connections.find(c => c.id === 'legacy').from.portId);
assert.ok(reloaded.connections.find(c => c.id === 'legacy').to.portId);
await evaluate(`document.querySelector('[data-action="show-connections"]').click()`);
assert.equal(await evaluate(`document.querySelectorAll('[data-cable-select]').length`), 2);
await evaluate(`localStorage.setItem('titan-workspace-v2', JSON.stringify({projects:[{name:'Old rack',buildings:[{id:'b',name:'B',floors:[{id:'f',floorName:'F',zones:[],assets:[{id:'r',type:'cabinet',name:'Rack'},{id:'s',type:'switch',name:'Old switch',rackId:'r',ports:[]}]}]}],cables:[]}]})); location.reload()`); await wait(700);
await evaluate(`document.querySelector('[data-asset-select="r"]').click()`);
await field('[name="rackUnits"]', '12');
await evaluate(`document.querySelector('[data-asset-select="s"]').click()`);
await field('[name="rackStart"]', '2'); await field('[name="rackHeight"]', '2');
assert.equal(await evaluate(`document.querySelector('[name="rackStart"]').value`), '2');
assert.equal(await evaluate(`document.querySelector('[name="rackHeight"]').value`), '2');
await send('Page.reload', { ignoreCache: true }); await wait(700);
await evaluate(`document.querySelector('[data-asset-select="s"]').click()`);
assert.equal(await evaluate(`document.querySelector('[name="rackStart"]').value`), '2');
console.log('Configurable ports, rack occupancy, stable connection IDs and reload passed.');
socket.close();
